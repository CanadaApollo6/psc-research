source('scripts/run_coloc_platform.R')
gwas<-data.frame(snp=paste0('s',1:200),position=1:200,pvalue=2*pnorm(-abs(c(10,rep(0,199)))),MAF=0.2,N=1000,case_fraction=0.3)
qtl<-data.frame(snp=gwas$snp,position=1:200,beta=c(1,rep(0,199)),varbeta=0.01,pvalue=gwas$pvalue,MAF=0.2,N=1000)
plan<-list(gwas=list(n=1000,cases=300),methods=list(priors=list(p1=1e-4,p2=1e-4)))
reference<-baseline_pair(gwas,qtl,plan,1e-6)
result<-platform_pair(gwas,qtl,plan,1e-6)
names<-paste0('PP.H',0:4,'.abf')
stopifnot(isTRUE(all.equal(unlist(reference$summary[names]),unlist(result$summary[names]),tolerance=1e-12)))
gwas$N<-rep(c(14890,11386,3504),length.out=200)
gwas$case_fraction<-rep(c(2871/14890,2170/11386,701/3504),length.out=200)
vector<-platform_logbf(gwas)
scalar<-vapply(seq_len(nrow(gwas)),function(i)coloc:::approx.bf.p(gwas$pvalue[i],gwas$MAF[i],'cc',gwas$N[i],gwas$case_fraction[i])$lABF,numeric(1))
stopifnot(isTRUE(all.equal(vector,scalar,tolerance=1e-12)))
